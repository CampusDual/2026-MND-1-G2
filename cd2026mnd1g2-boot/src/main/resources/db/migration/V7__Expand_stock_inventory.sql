UPDATE stock
SET description = (
        SELECT subcategory.description
        FROM request_subcategories subcategory
        WHERE subcategory.subcategory_id = stock.subcategory_id
    ),
    stock_type = (
        SELECT CASE
            WHEN category.name LIKE 'Toallas y%' OR category.name = 'Ropa de cama'
                THEN 'REUSABLE'
            ELSE 'CONSUMABLE'
        END
        FROM request_subcategories subcategory
        JOIN request_categories category ON category.category_id = subcategory.category_id
        WHERE subcategory.subcategory_id = stock.subcategory_id
    ),
    warehouse_units = uds,
    laundry_units = 0;

ALTER TABLE stock ADD CONSTRAINT ck_stock_type
    CHECK (stock_type IN ('CONSUMABLE', 'REUSABLE'));
ALTER TABLE stock ADD CONSTRAINT ck_stock_minimum
    CHECK (minimum_stock >= 0);
ALTER TABLE stock ADD CONSTRAINT ck_stock_warehouse
    CHECK (warehouse_units >= 0);
ALTER TABLE stock ADD CONSTRAINT ck_stock_laundry
    CHECK (laundry_units >= 0);
ALTER TABLE stock ADD CONSTRAINT ck_stock_inventory_state
    CHECK (
        (stock_type = 'CONSUMABLE' AND uds = warehouse_units AND laundry_units = 0)
        OR (stock_type = 'REUSABLE' AND uds = warehouse_units + laundry_units)
    );

CREATE TABLE stock_movements (
    movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    movement_type VARCHAR(30) NOT NULL,
    quantity INTEGER NOT NULL,
    source_state VARCHAR(20),
    reason VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    actor_username VARCHAR(120) NOT NULL,
    worker_id BIGINT,
    service_request_id BIGINT,
    idempotency_key VARCHAR(160) NOT NULL UNIQUE,
    previous_warehouse INTEGER NOT NULL,
    previous_laundry INTEGER NOT NULL,
    previous_total INTEGER NOT NULL,
    next_warehouse INTEGER NOT NULL,
    next_laundry INTEGER NOT NULL,
    next_total INTEGER NOT NULL,
    CONSTRAINT fk_stock_movements_product FOREIGN KEY (product_id)
        REFERENCES stock (product_id),
    CONSTRAINT fk_stock_movements_worker FOREIGN KEY (worker_id)
        REFERENCES workers (worker_id),
    CONSTRAINT fk_stock_movements_request FOREIGN KEY (service_request_id)
        REFERENCES service_requests (service_request_id),
    CONSTRAINT ck_stock_movement_type
        CHECK (movement_type IN ('STOCK_ENTRY', 'CONSUMPTION', 'TO_LAUNDRY',
                                 'FROM_LAUNDRY', 'DISPOSAL')),
    CONSTRAINT ck_stock_movement_quantity CHECK (quantity > 0),
    CONSTRAINT ck_stock_movement_source
        CHECK (source_state IS NULL OR source_state IN ('WAREHOUSE', 'LAUNDRY')),
    CONSTRAINT ck_stock_movement_snapshots
        CHECK (
            previous_warehouse >= 0 AND previous_laundry >= 0 AND previous_total >= 0
            AND next_warehouse >= 0 AND next_laundry >= 0 AND next_total >= 0
        )
);
