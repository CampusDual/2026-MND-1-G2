CREATE TABLE stock (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    subcategory_id BIGINT NOT NULL UNIQUE,
    uds INTEGER DEFAULT 500 NOT NULL,
    CONSTRAINT fk_stock_subcategory FOREIGN KEY (subcategory_id)
        REFERENCES request_subcategories (subcategory_id),
    CONSTRAINT ck_stock_uds CHECK (uds >= 0)
);

INSERT INTO stock (name, subcategory_id, uds)
SELECT subcategory.name, subcategory.subcategory_id, 500
FROM request_subcategories subcategory
JOIN request_categories category
  ON category.category_id = subcategory.category_id
WHERE category.type = 'SERVICE';
